//! The panel model's own state (everything that is not a QML property) and its starting values.

use std::sync::Arc;
use std::sync::atomic::AtomicBool;
use std::sync::mpsc::Sender;

use cxx_qt_lib::QString;
use notify_apps::AppEntry;
use notify_panel_core::draft::{self, Draft, SimInput};
use notify_panel_core::{shell, view};
use notify_panel_core::view::Conn;
use notify_panel_core::worker::Cmd;
use notify_protocol::{DecidedIdx, HistoryEntry};

pub struct PanelModelRust {
    pub(crate) connected: bool,
    pub(crate) state: QString,
    pub(crate) state_message: QString,
    pub(crate) daemon_version: QString,
    pub(crate) connections: i32,
    pub(crate) dnd: bool,
    pub(crate) focus_mode: QString,
    pub(crate) focus_modes_json: QString,
    pub(crate) focus_draft_json: QString,
    pub(crate) holding: QString,
    pub(crate) hold_text: QString,
    pub(crate) active: i32,
    pub(crate) queued: i32,
    pub(crate) zones_json: QString,
    pub(crate) history_json: QString,
    pub(crate) history_total: i32,
    pub(crate) history_shown: i32,
    pub(crate) rules_json: QString,
    pub(crate) rules_count: i32,
    pub(crate) draft_zones_json: QString,
    pub(crate) dirty: bool,
    pub(crate) draft_valid: bool,
    pub(crate) checking: bool,
    pub(crate) draft_error: QString,
    pub(crate) external_changed: bool,
    pub(crate) conflict: bool,
    pub(crate) save_message: QString,
    pub(crate) rules_path_text: QString,
    pub(crate) sim_json: QString,
    pub(crate) settings_json: QString,
    pub(crate) autostart: bool,
    pub(crate) update_state: QString,
    pub(crate) update_latest: QString,
    pub(crate) update_message: QString,
    pub(crate) update_page: QString,
    pub(crate) tray_available: bool,
    pub(crate) test_mode: bool,
    pub(crate) rules_overridden: bool,
    pub(crate) apps_json: QString,
    pub(crate) apps_scanning: bool,
    pub(crate) system_json: QString,
    // not exposed to QML
    pub(crate) tray: Option<notify_panel_core::tray::TrayHandle>,
    pub(crate) tray_show_text: bool,
    pub(crate) tx: Option<Sender<Cmd>>,
    pub(crate) stop: Arc<AtomicBool>,
    pub(crate) history_all: Vec<HistoryEntry>,
    pub(crate) filter_query: String,
    pub(crate) filter_missed: bool,
    // rules editor state
    pub(crate) draft: Draft,
    pub(crate) draft_loaded: bool,
    pub(crate) latest_raw: String,
    pub(crate) conflict_disk: String,
    pub(crate) error_idx: Option<usize>,
    pub(crate) validate_token: u64,
    pub(crate) sim_token: u64,
    pub(crate) sim: SimInput,
    pub(crate) sim_matched: Vec<usize>,
    pub(crate) sim_decided: DecidedIdx,
    pub(crate) apps: Vec<AppEntry>,
    pub(crate) apps_token: u64,
}

impl Default for PanelModelRust {
    fn default() -> Self {
        let c = Conn::Connecting;
        Self {
            connected: false,
            state: QString::from(c.code()),
            state_message: QString::from(&c.message()),
            daemon_version: QString::from(""),
            connections: 0,
            dnd: false,
            focus_mode: QString::from(""),
            focus_modes_json: QString::from("[]"),
            focus_draft_json: QString::from("[]"),
            holding: QString::from(""),
            hold_text: QString::from(view::hold_text(false, "")),
            active: 0,
            queued: 0,
            zones_json: QString::from("[]"),
            history_json: QString::from("[]"),
            history_total: 0,
            history_shown: 0,
            rules_json: QString::from("[]"),
            rules_count: 0,
            draft_zones_json: QString::from("[]"),
            dirty: false,
            draft_valid: false,
            checking: false,
            draft_error: QString::from(""),
            external_changed: false,
            conflict: false,
            save_message: QString::from(""),
            rules_path_text: QString::from(&draft::rules_path().display().to_string()),
            sim_json: QString::from("{}"),
            settings_json: QString::from("{}"),
            autostart: shell::autostart_enabled(&shell::config_home()),
            update_state: QString::from("idle"),
            update_latest: QString::from(""),
            update_message: QString::from(""),
            update_page: QString::from(""),
            tray_available: false,
            test_mode: std::env::var_os("NOTIFY_PANEL_TEST").is_some_and(|v| v == "1"),
            rules_overridden: std::env::var_os("NOTIFD_RULES").is_some_and(|v| !v.is_empty()),
            apps_json: QString::from("[]"),
            apps_scanning: false,
            system_json: QString::from("{}"),
            tray: None,
            tray_show_text: false,
            tx: None,
            stop: Arc::new(AtomicBool::new(false)),
            history_all: Vec::new(),
            filter_query: String::new(),
            filter_missed: false,
            draft: Draft::empty(),
            draft_loaded: false,
            latest_raw: String::new(),
            conflict_disk: String::new(),
            error_idx: None,
            validate_token: 0,
            sim_token: 0,
            sim: SimInput::default(),
            sim_matched: Vec::new(),
            sim_decided: DecidedIdx::default(),
            apps: Vec::new(),
            apps_token: 0,
        }
    }
}
