//! Embeds every QML file in `notifd/` (plus the schema) into the binary, so the list of daemon files can never fall out of step with the folder:
//! a file added to `notifd/` is shipped by `notify update` without anyone remembering to list it.

use std::fmt::Write;
use std::path::Path;

fn main() {
    let notifd = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../notifd").canonicalize().expect("notifd folder");
    println!("cargo:rerun-if-changed={}", notifd.display());
    let mut names: Vec<String> = std::fs::read_dir(&notifd)
        .expect("read notifd")
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".qml") || n == "rules.schema.json")
        .collect();
    names.sort();
    let mut code = String::from("/// Every file that makes up the daemon, with its text (generated by build.rs from notifd/).\npub const FILES: &[(&str, &str)] = &[\n");
    for n in &names {
        writeln!(code, "    ({n:?}, include_str!({:?})),", notifd.join(n).display().to_string()).unwrap();
    }
    code.push_str("];\n");
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("payload_files.rs"), code).unwrap();
}
